function getSavedLang() {
  const saved = localStorage.getItem("netflix_lang");
  return saved === "hi-IN" || saved === "en-IN" ? saved : "en-IN";
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N["en-IN"];
  const htmlLang = lang.startsWith("hi") ? "hi" : "en";

  document.documentElement.lang = htmlLang;
  document.title = dict.pageTitle;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key || dict[key] == null) return;
    if (el.hasAttribute("data-i18n-html")) {
      el.innerHTML = dict[key];
    } else {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key && dict[key] != null) el.setAttribute("aria-label", dict[key]);
  });

  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-label");
    if (key && dict[key] != null) {
      const label = document.querySelector(`label[for="${el.id}"]`);
      if (label) label.textContent = dict[key];
    }
  });

  const signInBtn = document.getElementById("signInBtn");
  if (signInBtn && localStorage.getItem("netflix_session") && localStorage.getItem("netflix_profile")) {
    signInBtn.textContent = dict.browse;
  } else if (signInBtn) {
    signInBtn.textContent = dict.signIn;
  }

  document.querySelectorAll("#headerLang, #footerLang").forEach((sel) => {
    if (sel) sel.value = lang;
  });

  localStorage.setItem("netflix_lang", lang);
}

function initI18n() {
  const lang = getSavedLang();
  applyLang(lang);

  document.querySelectorAll("#headerLang, #footerLang").forEach((sel) => {
    sel?.addEventListener("change", () => {
      applyLang(sel.value);
    });
  });
}

document.addEventListener("DOMContentLoaded", initI18n);
